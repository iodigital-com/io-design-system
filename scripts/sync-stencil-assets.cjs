/**
 * sync-stencil-assets.cjs
 * ========================
 * Copies the Stencil-built io-components assets from dist/ into the
 * io-storefront's public/ directory so Next.js can serve them.
 *
 * It also generates the storefront's custom-element React JSX typings and the
 * IoTagNames registry from the Stencil source-of-truth type output.
 *
 * Run via: npm run sync:stencil-assets
 * Called automatically by: npm run build:storefront:release
 */

const fs = require('fs');
const path = require('path');

const sourceDir = path.join(__dirname, '..', 'io-components', 'dist', 'io-components');
const targetDir = path.join(__dirname, '..', 'io-storefront', 'public', 'stencil');
const typesSourceFile = path.join(__dirname, '..', 'io-components', 'dist', 'types', 'components.d.ts');
const storefrontTypesFile = path.join(__dirname, '..', 'io-storefront', 'src', 'types', 'custom-elements.d.ts');
const storefrontTagNamesFile = path.join(
  __dirname,
  '..',
  'io-storefront',
  'src',
  'types',
  'io-tag-names.generated.ts'
);
const isCheckMode = process.argv.includes('--check');

if (!fs.existsSync(sourceDir)) {
  console.error(`[sync-stencil-assets] Source directory does not exist: ${sourceDir}`);
  console.error('[sync-stencil-assets] Run "npm run build:components" first.');
  process.exit(1);
}

if (!fs.existsSync(typesSourceFile)) {
  console.error(`[sync-stencil-assets] Stencil types file does not exist: ${typesSourceFile}`);
  console.error('[sync-stencil-assets] Run "npm run build:components" first.');
  process.exit(1);
}

function toKebabCase(componentName) {
  return componentName
    .replace(/^Io/, 'io-')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();
}

function parseTagsFromTypes(source) {
  const matches = Array.from(source.matchAll(/interface\s+HTML(Io[A-Za-z0-9]+)Element\s+extends\s+Components\.(Io[A-Za-z0-9]+)/g));

  const tags = matches.map(([, htmlName, componentName]) => ({
    htmlName,
    componentName,
    tagName: toKebabCase(componentName),
  }));

  const deduped = new Map(tags.map((entry) => [entry.tagName, entry]));
  return Array.from(deduped.values()).sort((left, right) => left.tagName.localeCompare(right.tagName));
}

function writeFileIfChanged(filePath, content) {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (current === content) {
    return false;
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

function assertFileMatches(filePath, expectedContent) {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (current !== expectedContent) {
    console.error(`[sync-stencil-assets] Drift detected: ${path.relative(path.join(__dirname, '..'), filePath)}`);
    return false;
  }

  return true;
}

function renderTagNamesFile(tags) {
  const unionLines = tags.map(({ tagName }) => `  | '${tagName}'`).join('\n');

  return `/**\n * Auto-generated by scripts/sync-stencil-assets.cjs from\n * io-components/dist/types/components.d.ts.\n * Do not edit manually.\n */\n\nexport type IoTagNames =\n${unionLines};\n`;
}

function renderCustomElementsFile(tags) {
  const elementMapEntries = tags
    .map(
      ({ tagName, htmlName, componentName }) =>
        `  '${tagName}': React.DetailedHTMLProps<React.HTMLAttributes<HTML${htmlName}Element>, HTML${htmlName}Element> & Partial<StencilJSX.${componentName}>;`
    )
    .join('\n');

  return `/* eslint-disable */\n/* tslint:disable */\n/**\n * Auto-generated by scripts/sync-stencil-assets.cjs from\n * io-components/dist/types/components.d.ts.\n * Do not edit manually.\n */\n\nimport type * as React from 'react';\nimport type { JSX as StencilJSX } from '../../../io-components/dist/types/components';\n\ndeclare module 'react' {\n  namespace JSX {\n    interface IntrinsicElements {\n${elementMapEntries}\n    }\n  }\n}\n`;
}

const stencilTypesSource = fs.readFileSync(typesSourceFile, 'utf8');
const tags = parseTagsFromTypes(stencilTypesSource);

if (tags.length === 0) {
  console.error('[sync-stencil-assets] Unable to derive io-* component tags from dist/types/components.d.ts.');
  process.exit(1);
}

const tagNamesContent = renderTagNamesFile(tags);
const customElementsContent = renderCustomElementsFile(tags);

if (isCheckMode) {
  const tagsOkay = assertFileMatches(storefrontTagNamesFile, tagNamesContent);
  const customElementsOkay = assertFileMatches(storefrontTypesFile, customElementsContent);

  if (!tagsOkay || !customElementsOkay) {
    console.error('[sync-stencil-assets] Generated storefront type artifacts are out of sync.');
    console.error('[sync-stencil-assets] Run "npm run sync:stencil-assets" and commit the updated files.');
    process.exit(1);
  }

  console.log('[sync-stencil-assets] ✓ Storefront generated typings are in sync with Stencil output.');
  process.exit(0);
}

fs.mkdirSync(targetDir, { recursive: true });
fs.cpSync(sourceDir, targetDir, { recursive: true, force: true });

const wroteCustomElements = writeFileIfChanged(storefrontTypesFile, customElementsContent);
const wroteTagNames = writeFileIfChanged(storefrontTagNamesFile, tagNamesContent);

console.log(`[sync-stencil-assets] ✓ Synced assets:`);
console.log(`  ${sourceDir}`);
console.log(`  → ${targetDir}`);
console.log(`[sync-stencil-assets] ✓ ${wroteCustomElements ? 'Generated' : 'Verified'} storefront custom-elements typings:`);
console.log(`  ${storefrontTypesFile}`);
console.log(`[sync-stencil-assets] ✓ ${wroteTagNames ? 'Generated' : 'Verified'} IoTagNames registry:`);
console.log(`  ${storefrontTagNamesFile}`);
